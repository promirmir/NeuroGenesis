"""Bounded neural activity regulation with explicit sensor evidence.

Implements a conservative homeostatic *research candidate*, not biological
fidelity or proof of improved intelligence. Works with the existing Brain API
without changing Brain.step() or the v0.4 brain snapshot schema.

Call observe(brain) immediately AFTER a Brain.step(); it may scale mature
input-to-hidden or recurrent synapses at the configured interval. The
controller's own rate history can be snapshotted separately.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
import math
from typing import Any


@dataclass(frozen=True)
class HomeostasisConfig:
    target_rate: float = 0.10
    rate_decay: float = 0.95
    adapt_every: int = 32
    gain: float = 0.3
    max_relative_change: float = 0.03
    dead_zone: float = 0.025
    min_input_steps: int = 8

    def __post_init__(self) -> None:
        for name in ('target_rate', 'rate_decay', 'gain', 'max_relative_change', 'dead_zone'):
            x = getattr(self, name)
            if type(x) not in (int, float) or not math.isfinite(x):
                raise ValueError(f'{name} must be finite')
        if not 0 < self.target_rate < 1:
            raise ValueError('target_rate must be in (0, 1)')
        if not 0 < self.rate_decay < 1:
            raise ValueError('rate_decay must be in (0, 1)')
        if not 0 < self.gain <= 1:
            raise ValueError('gain must be in (0, 1]')
        if not 0 < self.max_relative_change <= 0.1:
            raise ValueError('max_relative_change must be in (0, 0.1]')
        if not 0 <= self.dead_zone < 1:
            raise ValueError('dead_zone must be in [0, 1)')
        if type(self.adapt_every) is not int or not 4 <= self.adapt_every <= 100000:
            raise ValueError('adapt_every must be an int in [4, 100000]')
        if type(self.min_input_steps) is not int or not 1 <= self.min_input_steps <= self.adapt_every:
            raise ValueError('min_input_steps must be in [1, adapt_every]')


class HomeostaticRegulator:
    """EWMA activity sensor with bounded postsynaptic weight scaling.

    This is not a brain replacement: it observes real spikes generated by Brain.
    Sensory-input neurons are never regulated. With no recent sensory evidence,
    weights are not amplified in an attempt to make a disconnected network fire.
    """

    VERSION = 1

    def __init__(self, config: HomeostasisConfig | None = None) -> None:
        self.config = config or HomeostasisConfig()
        self.rates: list[float] = []
        self.steps = 0
        self.input_steps = 0
        self.scaling_events = 0
        self.scaled_synapses = 0

    @classmethod
    def attach(cls, brain: Any,
               config: HomeostasisConfig | None = None) -> 'HomeostaticRegulator':
        """Attach to an existing v0.4 brain without resetting learned state.

        Rate history begins uncalibrated; the supervisor must then observe each
        subsequent Brain.step() exactly once. Neural-state serialization stays
        unchanged and the supervisor can be persisted independently.
        """
        n = len(brain.voltages)
        if (type(brain.steps) is not int or brain.steps < 0 or
                n < brain.config.initial_neurons or n > brain.config.max_neurons):
            raise ValueError('invalid existing brain state')
        result = cls(config)
        result.steps = brain.steps
        result.rates = [0.0] * n
        return result

    def observe(self, brain: Any) -> int:
        """Observe a genuine completed step; return count of scaled synapses.

        Reject invalid external state before touching the regulator or brain.
        The monotonic counter avoids interpreting the same step twice as evidence.
        """
        n = len(brain.spikes)
        if n == 0 or len(brain.traces) != n or len(brain.voltages) != n:
            raise ValueError('invalid neural dimensions')
        if not isinstance(brain.steps, int) or type(brain.steps) is bool or brain.steps != self.steps + 1:
            raise ValueError('brain steps must advance exactly once per observation')
        if any(type(spike) is not int or spike not in (0, 1) for spike in brain.spikes):
            raise ValueError('invalid spikes')
        width = brain.config.input_size
        if not isinstance(width, int) or type(width) is bool or not 1 <= width < n:
            raise ValueError('invalid input width')
        if len(brain.last_stimulus) != width or any(
            type(x) not in (int, float) or not math.isfinite(x) or x < 0 or x > 1
            for x in brain.last_stimulus
        ):
            raise ValueError('invalid stimulus')
        for edge in brain.synapses:
            if (type(edge.pre) is not int or type(edge.post) is not int or
                not 0 <= edge.pre < n or not width <= edge.post < n or
                type(edge.weight) not in (int, float) or
                not math.isfinite(edge.weight) or not 0 <= edge.weight <= brain.config.weight_limit):
                raise ValueError('invalid synapse state')
        if len(self.rates) > n:
            raise ValueError('neuron count shrank: use explicit controller migration')
        if len(self.rates) < n:
            self.rates.extend([0.0] * (n - len(self.rates)))
        c = self.config
        for i, spike in enumerate(brain.spikes):
            self.rates[i] = c.rate_decay * self.rates[i] + (1 - c.rate_decay) * spike
        self.steps += 1
        if any(brain.last_stimulus):
            self.input_steps += 1
        if self.steps % c.adapt_every != 0:
            return 0
        changed = 0
        if self.input_steps >= c.min_input_steps:
            factors = [1.0] * n
            for post in range(width, n):
                err = c.target_rate - self.rates[post]
                if abs(err) >= c.dead_zone:
                    raw = math.exp(c.gain * err)
                    factors[post] = max(1 - c.max_relative_change,
                                        min(1 + c.max_relative_change, raw))
            # Brain synapses are non-negative and bounded by its own config.
            for edge in brain.synapses:
                if edge.weight > 0 and factors[edge.post] != 1:
                    next_weight = max(0.0, min(brain.config.weight_limit,
                                               edge.weight * factors[edge.post]))
                    if next_weight != edge.weight:
                        edge.weight = next_weight
                        changed += 1
        self.input_steps = 0
        self.scaled_synapses += changed
        if changed:
            self.scaling_events += 1
        return changed

    def status(self) -> dict[str, Any]:
        return {
            'steps': self.steps,
            'observed_neurons': len(self.rates),
            'mean_observed_rate': None if not self.rates else sum(self.rates) / len(self.rates),
            'scaling_events': self.scaling_events,
            'scaled_synapses': self.scaled_synapses,
            'pending_input_steps': self.input_steps,
        }

    def to_dict(self) -> dict[str, Any]:
        return {'schema': self.VERSION, 'config': asdict(self.config),
                'rates': list(self.rates), 'steps': self.steps,
                'input_steps': self.input_steps, 'scaling_events': self.scaling_events,
                'scaled_synapses': self.scaled_synapses}

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> 'HomeostaticRegulator':
        if not isinstance(data, dict) or data.get('schema') != cls.VERSION:
            raise ValueError('unknown homeostasis schema')
        try:
            obj = cls(HomeostasisConfig(**data['config']))
            rates = data['rates']
            if not isinstance(rates, list) or len(rates) > 4096 or any(
                type(x) not in (int, float) or not math.isfinite(x) or not 0 <= x <= 1
                for x in rates
            ):
                raise ValueError('invalid rates')
            fields = ('steps', 'input_steps', 'scaling_events', 'scaled_synapses')
            if any(type(data[k]) is not int or data[k] < 0 for k in fields):
                raise ValueError('invalid counters')
            if data['input_steps'] >= obj.config.adapt_every:
                raise ValueError('invalid pending input count')
            obj.rates = list(rates)
            for k in fields:
                setattr(obj, k, data[k])
            return obj
        except (KeyError, TypeError, AttributeError) as exc:
            raise ValueError('malformed homeostasis snapshot') from exc
