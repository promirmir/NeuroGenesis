"""Leakage-free audit of when ACF's semantic proposals predict real next tags.

No assumptions about an improvement: all negative/zero/abstained results are
reported. This benchmark reads only eight binary semantic tags previously
generated by the bundled offline Qwen and stored in a private SQLite DB.
No prompts, web access, model downloads or raw source text.
"""
from __future__ import annotations

import argparse
from contextlib import closing
import json
from pathlib import Path
import sqlite3
from typing import Sequence

from .acf import AdaptiveCognitiveFabric, _sample
from .acf_semantics import AXES, VERSION
from .semantic_policy import decide

MAX_ROWS = 2000


def evaluate(vectors: Sequence[Sequence[float]]) -> dict:
    if not isinstance(vectors, (list, tuple)) or len(vectors) > MAX_ROWS:
        raise ValueError("Expected up to 2000 semantic event vectors.")
    stream = [_sample(x, len(AXES)) for x in vectors]
    if any(any(a not in (0.0, 1.0) for a in x) for x in stream):
        raise ValueError("Only real validated eight-axis binary tags are accepted.")
    fabric = AdaptiveCognitiveFabric()
    eligible = 0
    correct = 0
    baseline_correct = 0
    skipped = {}
    for current in stream:
        # Decision is created entirely from PREVIOUS events.
        proposal = decide(fabric)
        if proposal.status == "eligible_for_local_prefetch":
            eligible += 1
            axis = AXES.index(proposal.predicted_axis)
            correct += int(current[axis] == 1.0)
            # Matched baseline evaluated only on precisely the SAME
            # selected events: persistence uses previous dominant topic.
            if fabric.last_sample is not None:
                last_axis = max(
                    range(len(AXES)), key=lambda i: (fabric.last_sample[i], -i))
                baseline_correct += int(current[last_axis] == 1.0)
        else:
            skipped[proposal.status] = skipped.get(proposal.status, 0) + 1
        fabric.observe(current)
    estimated = (
        round(correct / eligible, 5) if eligible else None)
    baseline = (
        round(baseline_correct / eligible, 5) if eligible else None)
    # Selective evaluation alone is NOT an unbiased controlled comparison.
    result = {
        "protocol": "semantic_acf_prequential_next_topic_shadow_v1",
        "observation_count": len(stream),
        "prefetch_decisions": eligible,
        "abstentions": len(stream) - eligible,
        "abstention_reasons": skipped,
        "next_topic_hit_rate_on_selected_events": estimated,
        "persistence_hit_rate_on_same_events": baseline,
        "measured_relative_hit_rate_advantage": (
            round(estimated - baseline, 5) if eligible else None),
        "user_task_improvement_proven": False,
        "selection_bias_eliminated": False,
        "requires_independent_holdout_and_task_outcomes": True,
        "no_private_text_read": True,
    }
    return result


def read_private_semantics(path: Path, *, limit: int = MAX_ROWS) -> list[list[float]]:
    if (not isinstance(path, Path) or not path.is_file()
            or path.is_symlink() or type(limit) is not int
            or not 1 <= limit <= MAX_ROWS):
        raise ValueError("Private semantic SQLite path missing or invalid.")
    with closing(sqlite3.connect(str(path), timeout=7)) as con:
        con.execute("PRAGMA query_only=ON")
        rows = con.execute(
            "SELECT features,tagger FROM observations "
            "ORDER BY id ASC LIMIT ?", (limit,)).fetchall()
    result = []
    for raw, tagger in rows:
        if type(tagger) is not str or tagger != VERSION or (
                type(raw) is not str or len(raw) > 1024):
            raise ValueError("Only pinned local Qwen semantic observations allowed.")
        try:
            tags = json.loads(raw, parse_constant=lambda _x: (_ for _ in ()).throw(
                ValueError("Invalid nonfinite semantic value")))
        except json.JSONDecodeError as exc:
            raise ValueError("Malformed semantic event JSON.") from exc
        result.append(_sample(tags, len(AXES)))
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Audit actual saved semantic ACF decisions; no network or raw text")
    parser.add_argument("--semantic-sqlite", required=True, type=Path)
    parser.add_argument("--limit", type=int, default=MAX_ROWS)
    args = parser.parse_args(argv)
    report = evaluate(read_private_semantics(
        args.semantic_sqlite, limit=args.limit))
    print(json.dumps(report, ensure_ascii=False, allow_nan=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
